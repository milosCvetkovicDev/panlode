"""Claude Code hook handlers: pre-write guard, post-write check, stop check, session brief.

Exit code 2 is the hook protocol's "blocking" code: for PreToolUse it stops the write, for PostToolUse
it shows stderr to Claude, for Stop it keeps Claude working. Only pre-write blocks on unreadable input;
a crash inside any hook is shown to Claude rather than swallowed.
"""

import json
import os
import re
import tempfile
import unicodedata
from dataclasses import dataclass
from datetime import date
from pathlib import Path

from ideaengine.report import render_brief, render_index
from ideaengine.workspace import check, is_record_path, load

INDEX_FILE = "INDEX.md"
MAX_STOP_LINES = 20

PRODUCT_SUFFIXES = (".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".go", ".rs", ".java", ".cs", ".tf", ".sql")
PRODUCT_PREFIXES = ("dockerfile", "docker-compose", "tsconfig")
LOCKFILES = (
    "package-lock.json", "npm-shrinkwrap.json", "pnpm-lock.yaml", "yarn.lock", "bun.lock", "bun.lockb",
    "cargo.lock", "go.sum", "poetry.lock", "composer.lock", "gemfile.lock",
)
GUARDED_DIRS = ("scripts", ".claude", ".git")
GUARDED_FILES = (".mcp.json",)
# Modes in which an ask shows the user a prompt. In the others (bypassPermissions, auto, dontAsk, or a mode
# added later) Claude Code may approve it unseen, so a guarded write is refused there instead.
ASK_MODES = ("default", "acceptEdits", "plan")

GUARDED_REASON = ("An edit to scripts/, .claude/, .git/ or .mcp.json changes what runs later without a prompt "
                  "(the engine the hooks call, Claude Code settings, git hooks, MCP servers); confirm it")
GUARDED_DENY_REASON = ("A write to scripts/, .claude/, .git/ or .mcp.json changes what runs later without a prompt, "
                       "and in {mode} mode a confirmation may be approved without being shown; ask the user to make "
                       "this edit themselves or to switch to the default mode")
PRODUCT_REASON = "This workspace is for discovery and validation; build in a separate repo"
INDEX_REASON = "INDEX.md is generated by scripts/engine.py; edit the records instead"
UNREADABLE_INPUT = "idea engine pre-write hook could not read its input; the write is blocked to stay safe"
CHECK_COMMAND = "python3 scripts/engine.py check"

class IndexLinkError(OSError):
    """INDEX.md is a symlink, so the index is not written."""


_ID_LINE = re.compile(r"^id:\s*[\"']?([a-z]+-\d+)", re.MULTILINE)


@dataclass(frozen=True)
class HookResult:
    exit_code: int = 0
    stdout: str = ""
    stderr: str = ""


def _context(event_name: str, text: str) -> HookResult:
    return HookResult(stdout=json.dumps({"hookSpecificOutput": {"hookEventName": event_name, "additionalContext": text}}))


def _decision(decision: str, reason: str) -> HookResult:
    return HookResult(stdout=json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse", "permissionDecision": decision, "permissionDecisionReason": reason,
    }}))


def _deny(reason: str) -> HookResult:
    return _decision("deny", reason)


def _file_path(event: dict) -> str | None:
    tool_input = event.get("tool_input")
    value = tool_input.get("file_path") if isinstance(tool_input, dict) else None
    return value if isinstance(value, str) and value else None


def _absolute(file_path: str, event: dict, root: Path) -> str:
    """The path as the tool reads it: ~ expanded, a relative path taken from the session's cwd."""
    path = os.path.expanduser(file_path)
    if os.path.isabs(path):
        return path
    cwd = event.get("cwd")
    return os.path.join(cwd if isinstance(cwd, str) and os.path.isabs(cwd) else root, path)


def _lexical_rel(file_path: str, root: Path) -> str | None:
    """Workspace-relative path with .. collapsed before links are followed, as a tool that normalizes the
    path first would write it; None outside the workspace."""
    rel = _relative_by_identity(Path(os.path.normpath(os.path.join(root, file_path))), root)
    return None if rel is None else _on_disk_case(root, rel)


def _resolved(file_path: str, root: Path) -> Path:
    path = Path(file_path)
    return (path if path.is_absolute() else root / path).resolve()


def _rel_path(file_path: str, root: Path) -> str | None:
    """Repo-relative POSIX path, or None outside the root. Both sides resolved (macOS /var → /private/var)."""
    path, root = _resolved(file_path, root), root.resolve()
    try:
        rel = path.relative_to(root).as_posix()
    except ValueError:
        rel = _relative_by_identity(path, root)
    return None if rel is None else _on_disk_case(root, rel)


def _relative_by_identity(path: Path, root: Path) -> str | None:
    # resolve() keeps a name as typed, and macOS volumes ignore case and Unicode normalization by default,
    # so look for the root among the existing folders above the path by identity.
    for parent in path.parents:
        try:
            if parent.samefile(root):
                return path.relative_to(parent).as_posix()
        except OSError:
            continue
    return None


def _on_disk_case(root: Path, rel: str) -> str:
    # The record checks compare names exactly, while macOS volumes ignore case and Unicode normalization,
    # so spell each existing part of the path as its folder lists it.
    parts, here = rel.split("/"), root
    for i, part in enumerate(parts):
        try:
            names = os.listdir(here)
        except OSError:
            break
        if part not in names:
            same = [n for n in names if _fold(n) == _fold(part)]
            try:
                if len(same) != 1 or not (here / part).samefile(here / same[0]):
                    break
            except OSError:
                break
            parts[i] = same[0]
        here = here / parts[i]
    return "/".join(parts)


def _fold(name: str) -> str:
    return unicodedata.normalize("NFC", name).casefold()


def _is_guarded(rel: str) -> bool:
    # The hooks run scripts/engine.py on every write and session, git runs .git/hooks, and Claude Code
    # starts what .mcp.json names, so an edit there becomes code that runs without a Bash prompt.
    # Casefold: macOS paths are case-insensitive.
    first = rel.split("/", 1)[0].casefold()
    return first in GUARDED_DIRS or rel.casefold() in GUARDED_FILES


def _in_guarded_place(path: Path, root: Path) -> bool:
    """True when the resolved path is, or lies inside, where a guarded folder or file really is: a guarded
    folder may be a link out of the workspace, and a write may name its target directly or through another
    link."""
    places = [(root / name).resolve() for name in GUARDED_DIRS + GUARDED_FILES]
    for candidate in (path, *path.parents):
        for place in places:
            try:
                if candidate == place or candidate.samefile(place):
                    return True
            except OSError:
                continue
    return False


def _guarded_decision(event: dict) -> HookResult:
    mode = event.get("permission_mode")
    if mode is None or mode in ASK_MODES:
        return _decision("ask", GUARDED_REASON)
    return _deny(GUARDED_DENY_REASON.format(mode=mode))


def _is_product_file(rel: str) -> bool:
    name = rel.rsplit("/", 1)[-1].casefold()
    if name.endswith(".md"):  # notes such as docker-compose-notes.md are research, not product
        return False
    return (
        name.endswith(PRODUCT_SUFFIXES) or name == "package.json" or name in LOCKFILES
        or name.startswith(PRODUCT_PREFIXES)
    )


def write_index(root: Path) -> bool:
    """Regenerate INDEX.md; write only when the content changed, so mtime stays put otherwise."""
    data = render_index(load(root)[0]).encode("utf-8")
    path = root / INDEX_FILE
    if path.is_symlink():
        raise IndexLinkError(f"{INDEX_FILE} is a symlink; the index is never written through one, so replace the link "
                             "with a plain file or remove it")
    if path.is_file() and path.read_bytes() == data:
        return False
    # A new file renamed over the old name, so a hard link to INDEX.md is never written through.
    fd, tmp = tempfile.mkstemp(dir=root, prefix=f".{INDEX_FILE}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise
    return True


def pre_write(event: dict, root: Path) -> HookResult:
    file_path = _file_path(event)
    if file_path is None:
        return HookResult(2, "", UNREADABLE_INPUT)
    file_path = _absolute(file_path, event, root)
    # Both readings of the path: with links followed (where the kernel writes) and with .. collapsed first
    # (where a tool that normalizes the path writes). A link may lead either one out of the workspace.
    names = [r for r in (_rel_path(file_path, root), _lexical_rel(file_path, root)) if r is not None]
    if any(r.casefold() == INDEX_FILE.casefold() for r in names):
        return _deny(INDEX_REASON)
    if any(_is_guarded(r) for r in names) or _in_guarded_place(_resolved(file_path, root), root):
        return _guarded_decision(event)
    if not names:
        return HookResult()
    if any(_is_product_file(r) for r in names):
        return _deny(PRODUCT_REASON)
    reason = _overwrite_reason(event, root, names[0])
    return _deny(reason) if reason else HookResult()


def _overwrite_reason(event: dict, root: Path, rel: str) -> str | None:
    """A Write that would replace a record with a different id (two titles with the same slug)."""
    tool_input = event.get("tool_input")
    content = tool_input.get("content") if isinstance(tool_input, dict) else None
    target = root / rel
    if event.get("tool_name") != "Write" or not isinstance(content, str) or not is_record_path(rel) or not target.is_file():
        return None
    old = _ID_LINE.search(target.read_text(encoding="utf-8", errors="replace"))
    new = _ID_LINE.search(content)
    if old and new and old.group(1) != new.group(1):
        return (f"{rel} already holds {old.group(1)}; writing {new.group(1)} would overwrite it. "
                "Use another file name (add -2 before .md).")
    return None


def post_write(event: dict, root: Path) -> HookResult:
    file_path = _file_path(event)
    file_path = _absolute(file_path, event, root) if file_path else None
    rel = (_rel_path(file_path, root) or _lexical_rel(file_path, root)) if file_path else None
    if rel is None or not is_record_path(rel):
        return HookResult()
    if not (root / rel).is_file():  # deleted or renamed before this hook ran
        index_error = _try_write_index(root)
        return HookResult(2, "", index_error + "\n") if index_error else HookResult()
    issues = [i for i in check(root) if i.path == rel]
    index_error = _try_write_index(root)
    errors = [i for i in issues if i.level == "error"]
    if errors or index_error:
        lines = [f"{rel} has {len(errors)} error(s); fix them before moving on:"] if errors else []
        lines += [f"- {i.message}" for i in issues] if errors else []
        lines += [index_error] if index_error else []
        return HookResult(2, "", "\n".join(lines) + "\n")
    if issues:
        return _context("PostToolUse", f"{rel} warnings: " + "; ".join(i.message for i in issues))
    return HookResult()


def _try_write_index(root: Path) -> str | None:
    """The index error as a line, so a record's own errors still reach Claude."""
    try:
        write_index(root)
    except IndexLinkError as e:
        return f"{INDEX_FILE} was not regenerated: {e}"
    return None


def stop(event: dict, root: Path) -> HookResult:
    write_index(root)
    if event.get("stop_hook_active"):
        return HookResult()  # already blocked once in this stop cycle; never loop
    errors = [i for i in check(root) if i.level == "error"]
    if not errors:
        return HookResult()
    lines = [f"The idea engine check found {len(errors)} error(s):"]
    lines += [str(i) for i in errors[:MAX_STOP_LINES]]
    if len(errors) > MAX_STOP_LINES:
        lines.append(f"... {len(errors) - MAX_STOP_LINES} more; run {CHECK_COMMAND}")
    lines.append(
        "Files written through Bash skip the per-write check, so they surface here. Fix the errors in records "
        "this session wrote; for the others, list them for the user instead of guessing values. Then finish."
    )
    return HookResult(2, "", "\n".join(lines) + "\n")


def session_start(event: dict, root: Path, today: date) -> HookResult:
    brief = render_brief(load(root)[0], today)
    errors = [i for i in check(root) if i.level == "error"]
    if errors:
        brief += f"Engine check: {len(errors)} error(s); run {CHECK_COMMAND}\n"
    return _context("SessionStart", brief)


def run_hook(name: str, raw_stdin: str, root: Path, today: date) -> HookResult:
    """Parse the hook's stdin JSON and dispatch. Only pre-write blocks on bad input; a crash is shown to Claude."""
    try:
        event = json.loads(raw_stdin)
        if not isinstance(event, dict):
            raise ValueError("hook input is not a JSON object")
    except ValueError:
        return HookResult(2, "", UNREADABLE_INPUT) if name == "pre-write" else HookResult()
    try:
        if name == "pre-write":
            return pre_write(event, root)
        if name == "post-write":
            return post_write(event, root)
        if name == "stop":
            return stop(event, root)
        if name == "session-start":
            return session_start(event, root, today)
    except Exception as e:  # a hook must never print a traceback into the session
        if name == "pre-write":
            return HookResult(2, "", f"{UNREADABLE_INPUT} ({type(e).__name__}: {e})")
        failure = f"idea engine {name} hook failed: {type(e).__name__}: {e}; run {CHECK_COMMAND}"
        if name == "session-start":
            return _context("SessionStart", failure)
        if name == "stop" and event.get("stop_hook_active"):
            return HookResult(0, "", failure)  # never loop
        return HookResult(2, "", failure + "\n")
    raise ValueError(f"unknown hook: {name}")

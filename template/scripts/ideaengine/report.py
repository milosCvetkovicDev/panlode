"""Generated views: INDEX.md and the short session brief."""

import re
from datetime import date

from ideaengine.schema import SIGNAL_STATUSES, parse_date, parse_int
from ideaengine.workspace import MAX_VALIDATING, Record

INDEX_HEADER = "<!-- Generated by scripts/engine.py index. Do not edit by hand. -->"
MAX_BRIEF_LINES = 25
MAX_OVERDUE_SHOWN = 5
MINIMUM_LOOP = "Minimum loop: one /scout-online per week; ≥2 prospect contacts logged per running experiment."

_IDEA_ORDER = ("validating", "go", "shaped", "parked", "building-elsewhere", "killed")
_EXPERIMENT_ORDER = ("running", "planned", "done")
_LOG_ENTRY = re.compile(r"^- (\d{4}-\d{2}-\d{2})\b")


def _get(record: Record, key: str) -> str:
    value = record.fields.get(key, "")
    return ", ".join(value) if isinstance(value, list) else value


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _rank(value: str, order: tuple[str, ...]) -> int:
    return order.index(value) if value in order else len(order)


def _table(headers: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return lines


def _of_type(records: list[Record], kind: str) -> list[Record]:
    return [r for r in records if r.type == kind]


def render_index(records: list[Record]) -> str:
    ideas = sorted(
        _of_type(records, "idea"),
        key=lambda r: (_rank(_get(r, "status"), _IDEA_ORDER), -(parse_int(_get(r, "score_total")) or 0), r.id),
    )
    experiments = sorted(
        _of_type(records, "experiment"),
        key=lambda r: (_rank(_get(r, "status"), _EXPERIMENT_ORDER), _get(r, "deadline"), r.id),
    )
    signals = _of_type(records, "signal")
    open_signals = sorted(
        (r for r in signals if _get(r, "status") in ("new", "clustered")),
        key=lambda r: (-(parse_int(_get(r, "evidence")) or 0), r.id),
    )
    interviews = sorted(_of_type(records, "interview"), key=lambda r: (_get(r, "date"), r.rel_path), reverse=True)

    lines = [INDEX_HEADER, "", "# Idea engine index", "", f"## Ideas ({len(ideas)})", ""]
    lines += _table(
        ["id", "title", "status", "shape", "score", "next"],
        [[f"[{r.id}]({r.rel_path})", _get(r, "title"), _get(r, "status"), _get(r, "shape"),
          _get(r, "score_total"), _get(r, "next")] for r in ideas],
    )
    lines += ["", f"## Experiments ({len(experiments)})", ""]
    lines += _table(
        ["id", "idea", "method", "status", "deadline"],
        [[f"[{r.id}]({r.rel_path})", _get(r, "idea"), _get(r, "method"), _get(r, "status"), _get(r, "deadline")]
         for r in experiments],
    )
    counts = " · ".join(f"{s} {sum(_get(r, 'status') == s for r in signals)}" for s in SIGNAL_STATUSES)
    lines += ["", f"## Signals ({len(signals)})", "", counts, "", "Open signals (new and clustered):", ""]
    lines += _table(
        ["id", "title", "evidence", "status", "cluster"],
        [[f"[{r.id}]({r.rel_path})", _get(r, "title"), _get(r, "evidence"), _get(r, "status"), _get(r, "cluster")]
         for r in open_signals],
    )
    lines += ["", f"## Interviews ({len(interviews)})", "", "Latest five:", ""]
    lines += _table(
        ["date", "segment", "channel", "file"],
        [[_get(r, "date"), _get(r, "segment"), _get(r, "channel"), f"[{r.rel_path}]({r.rel_path})"]
         for r in interviews[:5]],
    )
    return "\n".join(lines) + "\n"


def _log_dates(body: str) -> list[date]:
    found, in_log = [], False
    for line in body.splitlines():
        if line.startswith("## "):
            in_log = line.strip() == "## Log"
        elif in_log and (match := _LOG_ENTRY.match(line)) and (day := parse_date(match.group(1))):
            found.append(day)
    return found


def _days_since(days: list[date], today: date) -> str:
    return str((today - max(days)).days) if days else "n/a"


def render_brief(records: list[Record], today: date) -> str:
    lines = [f"Idea engine — {today.isoformat()}"]
    if not records:
        return "\n".join(lines + ["Empty pipeline — start with /scout-online.", MINIMUM_LOOP]) + "\n"

    signals, ideas = _of_type(records, "signal"), _of_type(records, "idea")
    experiments = {r.id: r for r in _of_type(records, "experiment")}
    validating = sorted((r for r in ideas if _get(r, "status") == "validating"), key=lambda r: r.id)
    by_status = lambda rs, s: sum(_get(r, "status") == s for r in rs)  # noqa: E731
    lines.append(
        f"Signals: {len(signals)} ({by_status(signals, 'new')} new) · "
        f"Ideas: {len(ideas)} ({len(validating)}/{MAX_VALIDATING} validating) · "
        f"Experiments: {by_status(experiments.values(), 'running')} running, "
        f"{by_status(experiments.values(), 'planned')} planned"
    )
    for idea in validating[:MAX_VALIDATING]:
        exp = experiments.get(_get(idea, "next"))
        target = f"{exp.id} (deadline {_get(exp, 'deadline')})" if exp else f"{_get(idea, 'next') or 'no next'} (missing)"
        lines.append(f"- {idea.id} {_get(idea, 'title')} → {target}")

    overdue = sorted(
        (r for r in experiments.values()
         if _get(r, "status") != "done" and (d := parse_date(_get(r, "deadline"))) and d < today),
        key=lambda r: (_get(r, "deadline"), r.id),
    )
    if overdue:
        shown = ", ".join(f"{r.id} ({_get(r, 'deadline')})" for r in overdue[:MAX_OVERDUE_SHOWN])
        more = f" +{len(overdue) - MAX_OVERDUE_SHOWN} more" if len(overdue) > MAX_OVERDUE_SHOWN else ""
        lines.append(f"Overdue: {shown}{more}")

    captured = [d for r in signals if (d := parse_date(_get(r, "captured")))]
    logged = [d for r in experiments.values() for d in _log_dates(r.body)]
    lines += [
        f"Days since last signal: {_days_since(captured, today)}",
        f"Days since last log entry: {_days_since(logged, today)}",
        MINIMUM_LOOP,
    ]
    return "\n".join(lines[:MAX_BRIEF_LINES]) + "\n"

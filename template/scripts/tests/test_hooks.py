import json
import unittest
from datetime import date
from unittest.mock import patch
from pathlib import Path

from ideaengine.hooks import HookResult, post_write, pre_write, run_hook, session_start, stop
from tests.helpers import make_workspace, to_markdown, valid_experiment, valid_signal

TODAY = date(2026, 10, 23)
SIG = "signals/2026-10-23-invoice-rekey.md"


def ev(path) -> dict:
    return {"tool_name": "Write", "tool_input": {"file_path": str(path)}}


class PreWriteTest(unittest.TestCase):
    def setUp(self):
        self.root = make_workspace({}).resolve()

    def test_pre_write_denies_product_code_and_index(self):
        for rel in ["foo.ts", "INDEX.md", "package.json", "Dockerfile.dev", "app/tsconfig.base.json"]:
            out = json.loads(pre_write(ev(self.root / rel), self.root).stdout)
            self.assertEqual(out["hookSpecificOutput"]["permissionDecision"], "deny", rel)
        reason = json.loads(pre_write(ev(self.root / "INDEX.md"), self.root).stdout)
        self.assertEqual(
            reason["hookSpecificOutput"]["permissionDecisionReason"],
            "INDEX.md is generated by scripts/engine.py; edit the records instead",
        )

    def test_pre_write_allows(self):
        root = self.root
        for p in [root / "signals/x.md", root / "ideas/x/scripts/notes.md", root / "docs/.claude-notes.md",
                  Path("/tmp/elsewhere.ts")]:
            self.assertEqual(pre_write(ev(p), root), HookResult(), p)

    def test_pre_write_asks_before_editing_what_the_hooks_run(self):
        for rel in ["scripts/x.py", "scripts/ideaengine/text.py", "scripts/x.ts", ".claude/settings.json",
                    ".claude/hooks/x.js", "Scripts/x.py", ".CLAUDE/rules/ideas.md"]:
            for tool in ["Write", "Edit"]:
                event = {"tool_name": tool, "tool_input": {"file_path": str(self.root / rel)}}
                out = json.loads(pre_write(event, self.root).stdout)["hookSpecificOutput"]
                self.assertEqual(out["permissionDecision"], "ask", (tool, rel))
                self.assertIn("the hooks run", out["permissionDecisionReason"], (tool, rel))

    def test_pre_write_allows_markdown_notes_named_like_product_files(self):
        for rel in ["ideas/x/docker-compose-notes.md", "ideas/x/tsconfig-findings.md", "docs/plans/dockerfile-notes.md"]:
            self.assertEqual(pre_write(ev(self.root / rel), self.root), HookResult(), rel)

    def test_pre_write_denies_overwriting_a_record_with_another_id(self):
        root = make_workspace({SIG: to_markdown(valid_signal())}).resolve()

        def write(content):
            return pre_write({"tool_name": "Write", "tool_input": {"file_path": str(root / SIG), "content": content}}, root)

        out = json.loads(write(to_markdown(valid_signal(id="sig-0002"))).stdout)["hookSpecificOutput"]
        self.assertEqual(out["permissionDecision"], "deny")
        self.assertIn("already holds sig-0001", out["permissionDecisionReason"])
        self.assertEqual(write(to_markdown(valid_signal())), HookResult())
        self.assertEqual(pre_write({"tool_name": "Edit", "tool_input": {"file_path": str(root / SIG)}}, root), HookResult())

    def test_malformed_input(self):
        r = run_hook("pre-write", "", self.root, TODAY)
        self.assertEqual(r.exit_code, 2)
        self.assertIn("could not read", r.stderr)
        for name in ["post-write", "stop", "session-start"]:
            self.assertEqual(run_hook(name, "not json", self.root, TODAY), HookResult(), name)


class PostWriteTest(unittest.TestCase):
    def test_post_write_reports_errors(self):
        f = valid_signal()
        del f["pain"]
        root = make_workspace({SIG: to_markdown(f)})
        r = post_write(ev(root / SIG), root)
        self.assertEqual(r.exit_code, 2)
        self.assertIn(SIG, r.stderr)
        self.assertIn("missing required field", r.stderr)

    def test_post_write_valid_updates_index(self):
        root = make_workspace({SIG: to_markdown(valid_signal())})
        self.assertEqual(post_write(ev(root / SIG), root).exit_code, 0)
        self.assertIn("sig-0001", (root / "INDEX.md").read_text(encoding="utf-8"))

    def test_post_write_warning_only(self):
        rel = "experiments/exp-0001-invoice-outreach.md"
        root = make_workspace({
            SIG: to_markdown(valid_signal()),
            "ideas/invoice-import/idea.md": "---\nid: idea-0001\n---\n",  # broken idea; only exp-0001 is checked
            rel: to_markdown(valid_experiment(budget_eur="150")),
        })
        r = post_write(ev(root / rel), root)
        self.assertEqual(r.exit_code, 0)
        self.assertIn("budget", json.loads(r.stdout)["hookSpecificOutput"]["additionalContext"])

    def test_post_write_deleted_file(self):
        root = make_workspace({})
        self.assertEqual(post_write(ev(root / SIG), root), HookResult())

    def test_post_write_ignores_other_files(self):
        root = make_workspace({"notes.md": "hello"})
        self.assertEqual(post_write(ev(root / "notes.md"), root), HookResult())
        self.assertFalse((root / "INDEX.md").exists())


class StopAndStartTest(unittest.TestCase):
    def test_stop_blocks_once(self):
        broken = make_workspace({"signals/2026-10-23-a.md": "---\nid: sig-0001\n---\n"})
        self.assertEqual(stop({"stop_hook_active": False}, broken).exit_code, 2)
        self.assertEqual(stop({"stop_hook_active": True}, broken).exit_code, 0)
        self.assertTrue((broken / "INDEX.md").exists())

    def test_stop_asks_to_report_errors_it_did_not_cause(self):
        broken = make_workspace({"signals/2026-10-23-a.md": "---\nid: sig-0001\n---\n"})
        self.assertIn("list them for the user instead of guessing values", stop({"stop_hook_active": False}, broken).stderr)

    def test_session_start_reports_check_errors(self):
        broken = make_workspace({"signals/2026-10-23-a.md": "---\nid: sig-0001\n---\n"})
        context = json.loads(session_start({}, broken, TODAY).stdout)["hookSpecificOutput"]["additionalContext"]
        self.assertRegex(context, r"Engine check: \d+ error\(s\); run python3 scripts/engine.py check")
        clean = json.loads(session_start({}, make_workspace({}), TODAY).stdout)["hookSpecificOutput"]["additionalContext"]
        self.assertNotIn("Engine check", clean)

    def test_session_start_emits_brief(self):
        out = json.loads(session_start({}, make_workspace({}), TODAY).stdout)
        self.assertEqual(out["hookSpecificOutput"]["hookEventName"], "SessionStart")
        self.assertIn("Idea engine", out["hookSpecificOutput"]["additionalContext"])


class HookFailureTest(unittest.TestCase):
    """A crash inside a hook is shown to Claude instead of passing silently."""

    def setUp(self):
        self.root = make_workspace({SIG: to_markdown(valid_signal())})
        (self.root / "INDEX.md").mkdir()  # write_index cannot write over a directory

    def test_post_write_crash_is_shown(self):
        r = run_hook("post-write", json.dumps(ev(self.root / SIG)), self.root, TODAY)
        self.assertEqual(r.exit_code, 2)
        self.assertIn("idea engine post-write hook failed: IsADirectoryError", r.stderr)

    def test_stop_crash_blocks_once(self):
        self.assertEqual(run_hook("stop", '{"stop_hook_active": false}', self.root, TODAY).exit_code, 2)
        self.assertEqual(run_hook("stop", '{"stop_hook_active": true}', self.root, TODAY).exit_code, 0)

    def test_session_start_crash_is_in_context(self):
        with patch("ideaengine.hooks.render_brief", side_effect=RuntimeError("boom")):
            r = run_hook("session-start", "{}", self.root, TODAY)
        self.assertEqual(r.exit_code, 0)
        context = json.loads(r.stdout)["hookSpecificOutput"]["additionalContext"]
        self.assertIn("idea engine session-start hook failed: RuntimeError: boom", context)


if __name__ == "__main__":
    unittest.main()
